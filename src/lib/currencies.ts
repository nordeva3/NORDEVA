export function getCurrency(code: string) {
  return CURRENCIES.find((c) => c.code === String(code).toUpperCase());
}

export function formatMoney(amount: number, currency: string) {
  const code = MARKETPLACE_CURRENCY;
  try {
    return new Intl.NumberFormat(undefined, {
      style: "currency",
      currency: code,
      maximumFractionDigits: 2,
    }).format(amount);
  } catch {
    const c = getCurrency(code);
    return `${c?.symbol ?? code} ${amount.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
  }
}

export const PLATFORM_FEE_PCT = 0.15;

export function currencyExponent(_currency: string) {
  return 2;
}
export function toMinorUnits(amount: number, currency: string) {
  return Math.round(amount * 10 ** currencyExponent(currency));
}
